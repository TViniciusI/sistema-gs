#!/usr/bin/env python3
"""Export INPM table from Excel to Dart asset."""
import base64
import bisect
import struct
import zlib
from pathlib import Path

import xlrd

XLS = Path(r"c:\Users\vinic\Downloads\correção a 20 - Alcool.xls")
OUT = Path(__file__).resolve().parent.parent / "lib" / "data" / "inpm_table_data.dart"


def load_table():
    wb = xlrd.open_workbook(str(XLS))
    tab = wb.sheet_by_name("Tabela")
    headers = [
        r
        for r in range(tab.nrows)
        if str(tab.cell_value(r, 0)).strip().upper() == "INPM"
    ]
    if not headers:
        raise ValueError('Sheet "Tabela" has no INPM header rows')

    block_temps = []
    block_rows = []
    for header_row in headers:
        temps = [
            round(float(tab.cell_value(header_row, c)), 1)
            for c in range(1, tab.ncols)
            if tab.cell_value(header_row, c) != ""
        ]
        rows = []
        data_row = header_row + 1
        while data_row < tab.nrows:
            v = tab.cell_value(data_row, 0)
            if v == "" or str(v).strip().upper() == "INPM":
                break
            inpm = float(v)
            dens = [
                round(float(tab.cell_value(data_row, c + 1)), 2)
                for c in range(len(temps))
            ]
            rows.append((inpm, dens))
            data_row += 1
        block_temps.append(temps)
        block_rows.append(rows)

    merged_temps = list(block_temps[0])
    for temps in block_temps[1:]:
        merged_temps.extend(temps[1:])

    merged_rows = []
    for i, (inpm, _) in enumerate(block_rows[0]):
        dens = list(block_rows[0][i][1])
        for block in block_rows[1:]:
            dens.extend(block[i][1][1:])
        merged_rows.append((inpm, dens))

    merged_rows.sort(key=lambda x: x[0])
    return merged_temps, merged_rows


def row_dens(rows, temps, idx, temp):
    dens = rows[idx][1]
    if temp <= temps[0]:
        return dens[0]
    if temp >= temps[-1]:
        slope = (dens[-1] - dens[-2]) / (temps[-1] - temps[-2])
        return dens[-1] + slope * (temp - temps[-1])
    i = bisect.bisect_right(temps, temp) - 1
    f = (temp - temps[i]) / (temps[i + 1] - temps[i])
    return dens[i] + f * (dens[i + 1] - dens[i])


def rho_table(rows, temps, inpm, temp):
    inpm_vals = [r[0] for r in rows]
    if inpm <= inpm_vals[0]:
        return row_dens(rows, temps, 0, temp)
    if inpm >= inpm_vals[-1]:
        return row_dens(rows, temps, len(rows) - 1, temp)
    i = bisect.bisect_right(inpm_vals, inpm) - 1
    frac = (inpm - inpm_vals[i]) / (inpm_vals[i + 1] - inpm_vals[i])
    d0 = row_dens(rows, temps, i, temp)
    d1 = row_dens(rows, temps, i + 1, temp)
    return d0 + frac * (d1 - d0)


def find_inpm(rows, temps, rho, temp):
    inpm_vals = [r[0] for r in rows]
    lo, hi = inpm_vals[0], inpm_vals[-1]
    for _ in range(80):
        mid = (lo + hi) / 2
        if rho_table(rows, temps, mid, temp) < rho:
            hi = mid
        else:
            lo = mid
    return (lo + hi) / 2


def ctl_from_inpm(rows, temps, inpm, tct):
    rho20 = rho_table(rows, temps, inpm, 20.0)
    dt = 0.01
    drho = (
        rho_table(rows, temps, inpm, tct + dt)
        - rho_table(rows, temps, inpm, tct - dt)
    ) / (2 * dt)
    beta = -drho / rho20
    return 1 / (1 + beta * (tct - 20))


def main():
    temps, rows = load_table()
    print("temps", len(temps), temps[0], temps[-1])
    print("rows", len(rows), rows[0][0], rows[-1][0])

    cases = [
        ("user", 777.47, 32.67, 32.67),
        ("excel", 809.0, 20.0, 20.5),
        ("p2", 786.5, 23.5, 23.5),
    ]
    for name, rho, t, tct in cases:
        inpm = find_inpm(rows, temps, rho, t)
        d20 = rho_table(rows, temps, inpm, 20)
        ctl = ctl_from_inpm(rows, temps, inpm, tct)
        print(f"{name}: INPM={inpm:.2f} d20={d20:.2f} ctl={ctl:.4f}")

    flat = [v for _, dens in rows for v in dens]
    packed = struct.pack("<" + "f" * len(flat), *flat)
    compressed = zlib.compress(packed, 9)
    print("compressed", len(compressed), "bytes")

    b64 = base64.b64encode(compressed).decode("ascii")
    # Split base64 into chunks for Dart string concatenation
    chunk_size = 76
    b64_chunks = [b64[i : i + chunk_size] for i in range(0, len(b64), chunk_size)]
    b64_dart = "\n    ".join(f"'{c}'" for c in b64_chunks)
    dart = f"""// GENERATED by tool/export_inpm_table.py — do not edit by hand.
import 'dart:convert';
import 'dart:typed_data';

import 'package:archive/archive.dart';

const inpmMin = {rows[0][0]};
const inpmMax = {rows[-1][0]};
const inpmStep = {round(rows[1][0] - rows[0][0], 4)};
const tempMin = {temps[0]};
const tempMax = {temps[-1]};
const tempStep = {round(temps[1] - temps[0], 1)};
const tempCount = {len(temps)};
const inpmCount = {len(rows)};

final inpmDensities = _decodeInpmTable();

Float32List _decodeInpmTable() {{
  final inflated = Uint8List.fromList(
    ZLibDecoder().decodeBytes(
      base64Decode(
    {b64_dart},
      ),
    ),
  );
  return inflated.buffer.asFloat32List();
}}
"""
    OUT.write_text(dart, encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
