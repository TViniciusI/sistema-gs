#!/usr/bin/env python3
"""Export DNS_20 / FCV_20 coefficient tables from GS Excel to Dart."""
from pathlib import Path

import xlrd

XLS = Path(
    r"c:\Users\vinic\Downloads\GS- TABELA DE CONVERSÃO DOS DERIVADOS DE PETROLEO REV.01.xls"
)
OUT = Path(__file__).resolve().parent.parent / "lib" / "data" / "derivados_table_data.dart"


def load_coeffs(sheet_name: str):
    wb = xlrd.open_workbook(str(XLS))
    sheet = wb.sheet_by_name(sheet_name)
    rows = []
    for r in range(2, sheet.nrows):
        damb = sheet.cell_value(r, 0)
        if damb == "":
            continue
        coeffs = [float(sheet.cell_value(r, c)) for c in range(5, 9)]
        rows.append((float(damb), coeffs))
    return rows


def main():
    dns = load_coeffs("DNS_20")
    fcv = load_coeffs("FCV_20")
    print("dns rows", len(dns), "fcv rows", len(fcv))

    def fmt_rows(name, rows):
        lines = []
        for damb, (p1, p2, p3, p4) in rows:
            lines.append(f"  DerivadosCoeffsRow({damb}, {p1}, {p2}, {p3}, {p4}),")
        return f"const {name} = [\n" + "\n".join(lines) + "\n];\n"

    dart = f"""// GENERATED by tool/export_derivados_table.py — do not edit by hand.

class DerivadosCoeffsRow {{
  const DerivadosCoeffsRow(this.damb, this.p1, this.p2, this.p3, this.p4);

  final double damb;
  final double p1;
  final double p2;
  final double p3;
  final double p4;
}}

{fmt_rows('dns20Table', dns)}
{fmt_rows('fcv20Table', fcv)}
"""
    OUT.write_text(dart, encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
